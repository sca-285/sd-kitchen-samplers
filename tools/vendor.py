"""Regenerate lib_kitchen/canon/ from reForge and Neo source.

    python tools/vendor.py /path/to/reForge /path/to/Forge-Classic-Neo

Only host plumbing is rewritten (model sampling, CONST, post-CFG, opts, randn_like).
Where both WebUIs have a function, Neo's copy is taken.
"""

