                "sample_dpmpp_2s_ancestral_cfg_pp", "sample_dpmpp_sde_cfg_pp",
                "sample_dpmpp_3m_sde_cfg_pp",
                "sample_res_multistep_cfg_pp", "sample_res_multistep_ancestral",
                "sample_res_multistep_ancestral_cfg_pp",
